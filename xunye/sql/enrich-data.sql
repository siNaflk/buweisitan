       CASE WHEN seq.s <= 2 THEN 0 ELSE b.chapter_price END,
       seq.s,
       1
FROM book b
JOIN (
    SELECT 1 AS s, '启程' AS name UNION ALL
    SELECT 2, '相遇' UNION ALL
    SELECT 3, '风起' UNION ALL
